"""Check a strengthened loop wand against emitted native iterator Viper.

Pass the program-check.vpr dumped from mut_native_tail_suffix_pass. This
experiment strengthens the emitted loop wand with a checked prefix/suffix
relation and asserts the owner's final contents. It adds no assumptions and
uses the emitted constructor and next pledges. The strengthened wand is not
yet generated by Prusti from a Rust annotation.
"""

import argparse
import os
from pathlib import Path
import re
import subprocess
import tempfile
import time


OWNER = "p_Ref_mutable_snap(_1p, s_Slice_type(s_UInt_u32_type()))"
ITERATOR = "p_std$col$$col$slice$col$$col$IterMut_snap(_14p, s_UInt_u32_type())"


def old_owner(label: str) -> str:
    return f"old[{label}]({OWNER})"


def old_tail(label: str) -> str:
    return f"old[{label}]({ITERATOR}).s_std$col$$col$slice$col$$col$IterMut_3"


def old_count(label: str) -> str:
    return f"s_UInt_usize_value(old[{label}](p_UInt_usize_snap(_13p)))"


def relation(address: str, length: str, tail: str, count: str) -> str:
    """RHS facts: processed prefix is seven; remaining values come from LHS."""
    source = f"s_Slice_to_seq(p_Slice_snap({address}, s_UInt_u32_type()), {length})"
    remaining = (
        f"old[lhs](s_Slice_to_seq(p_Param_snap({tail}.s_Ref_mutable_0, "
        f"s_Slice_type(s_UInt_u32_type())).make_concrete_s_Slice, "
        f"s_UInt_usize_value({tail}.s_Ref_mutable_1.make_concrete_s_UInt_usize)))"
    )
    return (
        f" && 0 <= {length} && 0 <= {count} && {count} <= {length}"
        f" && (forall q: Int :: {{ {source}[q] }} 0 <= q && q < {count} ==> "
        f"{source}[q] == make_generic_s_UInt_u32(s_UInt_u32_cons(7)))"
        f" && {source}[{count}..] == {remaining}"
    )


def labelled_relation(owner_label: str, tail_label: str, count_label: str) -> str:
    owner = old_owner(owner_label)
    length = f"s_UInt_usize_value({owner}.s_Ref_mutable_1.make_concrete_s_UInt_usize)"
    return relation(owner + ".s_Ref_mutable_0", length, old_tail(tail_label), old_count(count_label))


def source_predicate(label: str) -> re.Pattern[str]:
    start = f"acc(p_Slice(old[{label}]({OWNER}.s_Ref_mutable_0),"
    return re.compile(re.escape(start) + r"\s*" + re.escape("s_UInt_u32_type()), write)"))


def strengthen(program: str) -> str:
    if "method m_visit(_0p: Ref, _1p: Ref)" not in program:
        raise ValueError("the emitted program does not contain the expected iterator fixture")
    # The constructor package establishes the empty-prefix case.
    entry = list(source_predicate("outer_package2").finditer(program))
    if len(entry) != 1:
        raise ValueError("unexpected constructor loop-wand shape")
    end = entry[0].end()
    program = (program[:end] + labelled_relation("outer_package2", "outer_package2", "outer_package2")
               + program[end:])

    # Bind the loop count alongside the already-bound owner and tail snapshots.
    marker = ("    invariant (let _lb1 ==\n"
              "        (p_std$col$$col$slice$col$$col$IterMut_snap(_14p, s_UInt_u32_type())) in\n")
    if program.count(marker) != 1:
        raise ValueError("unexpected loop-invariant wand")
    program = program.replace(
        marker,
        "    invariant (let _lb2 == (p_UInt_usize_snap(_13p)) in\n"
        + marker.replace("    invariant ", "        ", 1),
        1,
    )
    end_marker = "acc(p_Slice(_lb0, s_UInt_u32_type()), write)))"
    if program.count(end_marker) != 1:
        raise ValueError("unexpected loop-invariant owner predicate")
    length = "s_UInt_usize_value(_loop_ref6.s_Ref_mutable_1.make_concrete_s_UInt_usize)"
    extra = relation("_lb0", length, "_lb1.s_std$col$$col$slice$col$$col$IterMut_3",
                     "s_UInt_usize_value(_lb2)")
    program = program.replace(end_marker, "acc(p_Slice(_lb0, s_UInt_u32_type()), write)" + extra + ")))", 1)

    # Strengthen the backedge package, the previous wand in its footprint, and
    # its application. The second match is a plain conditional resource, not a
    # wand, so it remains unchanged. Existing next-pledge scripts prove the step.
    matches = list(source_predicate("outer_package5").finditer(program))
    if len(matches) != 4:
        raise ValueError("unexpected backedge proof-script shape")
    for index in (3, 2, 0):
        end = matches[index].end()
        if index == 0:
            extra = labelled_relation("outer_package5", "outer_package5", "outer_package5")
        else:
            extra = labelled_relation("outer_package5", "_before_25_4", "_before_25_4")
        program = program[:end] + extra + program[end:]

    # Both exit paths must consume the same strengthened loop wand.
    for label in ("outer_package6", "outer_package8"):
        matches = list(source_predicate(label).finditer(program))
        if len(matches) != 1:
            raise ValueError(f"unexpected exit wand: {label}")
        end = matches[0].end()
        program = (program[:end] + labelled_relation(label, "_before_25_4", "_before_25_4")
                   + program[end:])
    return program


def final_assertions(program: str, case: str) -> tuple[str, int | None]:
    marker = "  label package_post7\n  goto end\n"
    if program.count(marker) != 1:
        raise ValueError("unexpected reachable return block")
    length = f"s_UInt_usize_value({OWNER}.s_Ref_mutable_1.make_concrete_s_UInt_usize)"
    source = (f"s_Slice_to_seq(p_Param_snap({OWNER}.s_Ref_mutable_0, "
              f"s_Slice_type(s_UInt_u32_type())).make_concrete_s_Slice, {length})")

    def all_equal(value: int) -> str:
        return (f"  assert (forall j: Int :: {{ {source}[j] }} 0 <= j && j < {length} ==> "
                f"{source}[j] == make_generic_s_UInt_u32(s_UInt_u32_cons({value})))\n")

    prefix = "  label package_post7\n" + all_equal(7)
    extra = {"valid": "", "false": "  assert false\n", "wrong_prefix": all_equal(8)}[case]
    position = program.index(marker)
    line = program[:position].count("\n") + prefix.count("\n") + 1 if extra else None
    return program.replace(marker, prefix + extra + "  goto end\n", 1), line


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("viper_program", type=Path)
    parser.add_argument("--case", choices=("valid", "false", "wrong_prefix"))
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    program = strengthen(args.viper_program.read_text())
    java_home = os.environ.get("JAVA_HOME")
    java = str(Path(java_home) / "bin/java") if java_home else "java"
    env = os.environ.copy()
    env["Z3_EXE"] = str(root / "viper_tools/z3/bin/z3")
    command = [
        java, "-Xss512m", "-cp", str(root / "viper_tools/backends/viperserver.jar"),
        "viper.silicon.SiliconRunner", "--logLevel", "ERROR", "--enableMoreCompleteExhale",
        "--disableTerminationPlugin", "--assertTimeout", "10000", "--proverConfigArgs",
        "smt.qi.eager_threshold=1000 model.partial=false smt.arith.solver=6",
        "--numberOfParallelVerifiers", "1", "--timeout", "180", "--includeMethods", "m_visit",
    ]
    logs = root / "target/stdlib-im2-loop-wand-logs"
    logs.mkdir(parents=True, exist_ok=True)
    all_ok = True
    cases = [args.case] if args.case else ["valid", "false", "wrong_prefix"]
    with tempfile.TemporaryDirectory(prefix="stdlib-im2-loop-wand-", dir=root / "target") as tmp:
        for name in cases:
            modified, line = final_assertions(program, name)
            path = Path(tmp) / f"{name}.vpr"
            path.write_text(modified)
            print(f"Running {name} ...", flush=True)
            start = time.monotonic()
            try:
                result = subprocess.run(command + [str(path)], cwd=root, env=env, text=True,
                                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=240)
                output = result.stdout
                errors = re.findall(r"^\s*\[\d+\] (.+)$", output, re.MULTILINE)
                if name == "valid":
                    ok = result.returncode == 0 and "finished verification successfully" in output and not errors
                else:
                    ok = (result.returncode == 1 and len(errors) == 1
                          and errors[0].startswith("Assert might fail.")
                          and f"{name}.vpr@{line}." in errors[0])
                ok = ok and not re.search(r"Verification timed out|internal error|Exception|Parsing error", output)
            except subprocess.TimeoutExpired as error:
                output = error.stdout or b""
                if isinstance(output, bytes):
                    output = output.decode(errors="replace")
                output += "\nTest command exceeded 240 seconds.\n"
                ok = False
            (logs / f"{name}.log").write_text(output)
            print(f"{name}: {'PASS' if ok else 'FAIL'} ({time.monotonic() - start:.2f}s)", flush=True)
            all_ok &= ok
    if not all_ok:
        raise SystemExit(1)
    print(f"All loop-wand checks passed ({len(cases)} checks).")


if __name__ == "__main__":
    main()
